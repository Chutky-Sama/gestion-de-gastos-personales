#!/usr/bin/env python3
"""Packs Vite dist/ directory into desktop/embedded_assets.h for single-file Windows .exe compilation."""
import mimetypes
import os
from pathlib import Path

MIME_MAP = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".webmanifest": "application/manifest+json; charset=utf-8",
    ".ico": "image/x-icon",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".woff2": "font/woff2",
}


def get_mime(path: Path) -> str:
    ext = path.suffix.lower()
    if ext in MIME_MAP:
        return MIME_MAP[ext]
    guessed, _ = mimetypes.guess_type(str(path))
    return guessed or "application/octet-stream"


def main() -> None:
    dist_dir = Path("dist")
    if not dist_dir.is_dir():
        raise SystemExit("dist/ directory not found. Run npm run build first.")

    files = []
    for p in sorted(dist_dir.rglob("*")):
        if not p.is_file():
            continue
        # Skip legacy .woff when .woff2 is present to keep executable lightweight
        if p.suffix.lower() == ".woff":
            continue
        rel = "/" + p.relative_to(dist_dir).as_posix()
        data = p.read_bytes()
        mime = get_mime(p)
        files.append((rel, mime, data))

    out_lines = [
        "// Auto-generated by scripts/pack_assets.py — DO NOT EDIT MANUALLY",
        "#ifndef NEON_KAKEIBO_EMBEDDED_ASSETS_H",
        "#define NEON_KAKEIBO_EMBEDDED_ASSETS_H",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    const char* url_path;",
        "    const char* content_type;",
        "    const uint8_t* data;",
        "    size_t size;",
        "} EmbeddedAsset;",
        "",
    ]

    for idx, (rel, mime, data) in enumerate(files):
        hex_chunks = []
        for i in range(0, len(data), 20):
            slice_bytes = data[i : i + 20]
            hex_chunks.append("    " + ", ".join(f"0x{b:02x}" for b in slice_bytes))
        array_body = ",\n".join(hex_chunks) if hex_chunks else "    0x00"
        out_lines.append(f"static const uint8_t ASSET_DATA_{idx}[] = {{")
        out_lines.append(array_body)
        out_lines.append("};")
        out_lines.append("")

    out_lines.append("static const EmbeddedAsset EMBEDDED_ASSETS[] = {")
    for idx, (rel, mime, data) in enumerate(files):
        out_lines.append(
            f'    {{ "{rel}", "{mime}", ASSET_DATA_{idx}, {len(data)} }},'
        )
    out_lines.append("};")
    out_lines.append(f"static const size_t EMBEDDED_ASSETS_COUNT = {len(files)};")
    out_lines.append("")
    out_lines.append("#endif")
    out_lines.append("")

    os.makedirs("desktop", exist_ok=True)
    out_path = Path("desktop/embedded_assets.h")
    out_path.write_text("\n".join(out_lines), encoding="utf-8")

    total_bytes = sum(len(d) for _, _, d in files)
    print(f"Packed {len(files)} assets ({total_bytes / 1024:.1f} KB) into {out_path}")


if __name__ == "__main__":
    main()
